"""Inline the project logos into dashboard/index.html as CSS data URIs.

The dashboard is a single file served by server.py / mock_server.py (no static directory), so logos travel inside
index.html. Run this after changing anything in dashboard/logos/:

    python3 dashboard/logos/embed.py

It rewrites the block between the LOGOS:start / LOGOS:end markers in index.html. SVGs get a light, safe cleanup
(XML prolog, comments, <metadata>, Inkscape/Sodipodi editor attributes) before encoding; PNGs are embedded as-is.
See README.md in this directory for sources and licenses.
"""
import base64
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INDEX = os.path.join(HERE, "..", "index.html")
START, END = "/* LOGOS:start (generated by dashboard/logos/embed.py; do not edit by hand) */", "/* LOGOS:end */"

# css class suffix -> file
LOGOS = {
    "llmd": "llm-d.svg",
    "vllm": "vllm.png",
    "k8s": "kubernetes.svg",
    "k8s-icon": "kubernetes-icon.svg",
    "substrate": "agent-substrate.svg",
    "gke": "gke.svg",
    "sglang": "sglang.svg",
    "nvidia": "nvidia.svg",
    "amd": "amd.svg",
    "intel": "intel.svg",
    "gcloud": "google-cloud.svg",
}


def clean_svg(text):
    text = re.sub(r"<\?xml[^>]*\?>", "", text)
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"<metadata\b.*?</metadata>", "", text, flags=re.S)
    text = re.sub(r"<sodipodi:namedview\b.*?</sodipodi:namedview>", "", text, flags=re.S)
    text = re.sub(r"<sodipodi:namedview\b[^>]*/>", "", text)
    text = re.sub(r"\s+(inkscape|sodipodi):[\w\-]+=\"[^\"]*\"", "", text)
    text = re.sub(r"\s+xmlns:(inkscape|sodipodi)=\"[^\"]*\"", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def data_uri(path):
    with open(path, "rb") as f:
        raw = f.read()
    if path.endswith(".svg"):
        raw = clean_svg(raw.decode("utf-8")).encode("utf-8")
        mime = "image/svg+xml"
    else:
        mime = "image/png"
    return "data:%s;base64,%s" % (mime, base64.b64encode(raw).decode("ascii")), len(raw)


def main():
    lines, total = [START], 0
    for cls, fname in LOGOS.items():
        uri, n = data_uri(os.path.join(HERE, fname))
        total += n
        lines.append(".lg-%s{background-image:url(\"%s\")}" % (cls, uri))
    lines.append(END)
    block = "\n".join(lines)
    with open(INDEX, encoding="utf-8") as f:
        html = f.read()
    if START not in html or END not in html:
        sys.exit("markers not found in %s" % INDEX)
    pre, rest = html.split(START, 1)
    _, post = rest.split(END, 1)
    with open(INDEX, "w", encoding="utf-8") as f:
        f.write(pre + block + post)
    print("embedded %d logos, %d bytes raw" % (len(LOGOS), total))


if __name__ == "__main__":
    main()
